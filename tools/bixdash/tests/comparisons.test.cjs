const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = {module: {exports: {}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../dashboard/comparisons.js'), 'utf8'), context);
const {rowOf, totalTokens, plottable} = context.module.exports;
assert.equal(totalTokens({tokens:{input:10,cached:20,output:30,reasoning:25}}),60);
assert.equal(totalTokens({tokens:{input:10,output:30}}),null);
assert.equal(totalTokens({tokens_total:99}),99);
const pending = rowOf({run_id:'pending',latest:{cost_usd:0,n_model_calls:0}});
assert.equal(pending.score,null);
assert.equal(pending.cost,0);
assert.equal(plottable([pending],'cost',true).length,0);
const zero = rowOf({run_id:'zero',latest:{partial_score:0,score_is_final:true,cost_usd:0,elapsed_s:120,n_model_calls:3}});
assert.equal(zero.time,2);
assert.equal(plottable([zero],'cost',false).length,1);
const partial = rowOf({run_id:'partial',latest:{partial_score:.5,score_is_final:false,cost_usd:1}});
assert.equal(plottable([partial],'cost',false).length,0);
assert.equal(plottable([partial],'cost',true).length,1);
const missing = rowOf({run_id:'missing',latest:{partial_score:.5,score_is_final:true}});
assert.equal(plottable([missing],'cost',true).length,0);
assert.equal(rowOf({latest:{partial_score:NaN}}).score,null);
assert.equal(rowOf({latest:{partial_score:1.2}}).score,null);
console.log('Comparison data tests passed (missing scores, real zero, partial/final, token accounting).');

// Missing numeric task IDs can be inferred from another run of the same paper.
const inferred = rowOf({run_id:'paper__model__run',meta:{paper_id:'paper',description:'Baseline: original harness'},latest:{}}, {paper:'11'});
assert.equal(inferred.task, '11');
assert.equal(inferred.baseline, true);
assert.equal(rowOf({meta:{description:'v2b artifact-validator'},latest:{}}).baseline, false);
assert.equal(plottable([{score:0,final:true,cost:1,isSmoke:true}], 'cost', false).length, 0);
